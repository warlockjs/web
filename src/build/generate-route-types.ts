import { parseRoutePathParameters } from "../routing/route-path-parameters";

/** The final route snapshot passed from the page/API registration pipeline. */
export type RegisteredRouteTypeSnapshot = {
  name: string;
  path: string;
  method: string;
};

/** Inputs remain separate because page and API names may legitimately overlap. */
export type GenerateRouteTypesInput = {
  pages: readonly RegisteredRouteTypeSnapshot[];
  apiRoutes: readonly RegisteredRouteTypeSnapshot[];
};

/** Raised instead of choosing an arbitrary declaration when one registry name conflicts. */
export class ConflictingRouteTypeNameError extends Error {
  public constructor(
    public readonly registry: "page" | "api",
    public readonly routeName: string,
    public readonly first: RegisteredRouteTypeSnapshot,
    public readonly second: RegisteredRouteTypeSnapshot,
  ) {
    super(
      `Cannot generate ${registry} route types: ${JSON.stringify(routeName)} names conflicting routes ` +
        `${JSON.stringify(first.path)} (${JSON.stringify(first.method)}) and ` +
        `${JSON.stringify(second.path)} (${JSON.stringify(second.method)}).`,
    );
    this.name = "ConflictingRouteTypeNameError";
  }
}

function quote(value: string): string {
  return JSON.stringify(value);
}

function uniqueSorted(
  registry: "page" | "api",
  snapshots: readonly RegisteredRouteTypeSnapshot[],
): RegisteredRouteTypeSnapshot[] {
  const byName = new Map<string, RegisteredRouteTypeSnapshot>();

  for (const snapshot of snapshots) {
    const existing = byName.get(snapshot.name);
    if (existing === undefined) {
      byName.set(snapshot.name, snapshot);
      continue;
    }
    if (existing.path !== snapshot.path || existing.method !== snapshot.method)
      throw new ConflictingRouteTypeNameError(registry, snapshot.name, existing, snapshot);
  }

  return [...byName.values()].sort(
    (left, right) => left.name.localeCompare(right.name) || left.path.localeCompare(right.path),
  );
}

function paramsType(path: string): string {
  const parsed = parseRoutePathParameters(path);
  if (parsed.type === "broad") return "Record<string, RouteParamValue>";
  if (parsed.parameters.length === 0) return "{}";

  return `{ ${parsed.parameters
    .map((parameter) => `${quote(parameter.name)}${parameter.optional ? "?" : ""}: RouteParamValue`)
    .join("; ")} }`;
}

function emitRegistry(
  interfaceName: "PageRouteRegistry" | "ApiRouteRegistry",
  snapshots: readonly RegisteredRouteTypeSnapshot[],
  includesMethod: boolean,
): string[] {
  const lines = [`  interface ${interfaceName} {`];

  for (const snapshot of snapshots) {
    const fields = [
      `path: ${quote(snapshot.path)}`,
      `params: ${paramsType(snapshot.path)}`,
      ...(includesMethod ? [`method: ${quote(snapshot.method.toUpperCase())}`] : []),
    ];
    lines.push(`    ${quote(snapshot.name)}: { ${fields.join("; ")} };`);
  }

  lines.push("  }");
  return lines;
}

/**
 * Emit a deterministic, application-owned declaration module. This function is
 * pure: the later build slice owns atomic replacement/deletion of its output.
 */
export function generateRouteTypes(input: GenerateRouteTypesInput): string {
  const pages = uniqueSorted("page", input.pages);
  const apiRoutes = uniqueSorted("api", input.apiRoutes);

  return [
    "// AUTO-GENERATED by @warlock.js/web -- do not edit.",
    'import type { RouteParamValue } from "@warlock.js/web";',
    "",
    'declare module "@warlock.js/web" {',
    ...emitRegistry("PageRouteRegistry", pages, false),
    "",
    ...emitRegistry("ApiRouteRegistry", apiRoutes, true),
    "}",
    "",
    "export {};",
    "",
  ].join("\n");
}
