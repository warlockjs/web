/**
 * The CLIENT half of the build→runtime handoff: the source of a generated
 * module that carries the page graph into the BROWSER.
 *
 * `generate-pages-barrel.ts` is the server half. The two are deliberately not
 * one function, because they want opposite things from the same recipe: the
 * server barrel emits STATIC `import * as` so every page lands in the one
 * server bundle and its route can be read off the module at boot, while the
 * browser must never download page B to render page A — so every module
 * reference here is a dynamic `import()`, and `name`/`path` are baked in as
 * DATA so the client runtime can match a route before loading anything.
 *
 * This function is PURE. It reads no filesystem, writes no file, and does not
 * call {@link discoverPages} — the caller passes the already-discovered graph
 * in. That is what keeps the "one discovery run, one graph" invariant: names
 * and paths agree with the server's because there is only ever one scan, not
 * because two scanners were written to match.
 *
 * Module RESOLUTION is the one thing that legitimately differs between the dev
 * provider and the production provider, so it is injected as
 * {@link GenerateClientRegistryOptions.toImportSpecifier} rather than computed
 * here. No provider-specific data — no Vite ids, no `/@fs/` prefixes, no
 * hashed chunk urls, no HMR metadata — reaches the emitted entry, and every
 * other property stays testable with a trivial mapper.
 */
import type { DiscoveredPage } from "./discover-pages";

export type GenerateClientRegistryOptions = {
  /**
   * The discovered page graph, IN THE ORDER DISCOVERY GAVE IT.
   *
   * `discoverPages` already sorts by POSIX source-file path
   * (`discover-pages.ts:368`, comparator at `discover-pages.ts:248-250`), so
   * this emitter preserves that order rather than imposing a second one: two
   * orderings of one graph is exactly the drift the shared scan exists to
   * prevent. Serialization stability only — nothing emitted here implies
   * matching precedence, which is a property of the route grammar.
   */
  pages: readonly DiscoveredPage[];
  /** Maps an absolute source file path to the specifier the emitted module will import. */
  toImportSpecifier: (absoluteFilePath: string) => string;
};

/** The name of the array the generated module exports. */
export const CLIENT_REGISTRY_EXPORT_NAME = "pages";

/** The specifier the generated module imports its entry type from. */
const CLIENT_RUNTIME_SPECIFIER = "@warlock.js/web/client/runtime";

/**
 * Raised when two pages claim one route name.
 *
 * `discoverPages` promises uniqueness already (`discover-pages.ts:370`). This
 * asserts it anyway: the alternative is trusting an upstream promise and
 * emitting a registry in which one page is silently unreachable, which costs
 * far more to diagnose than the check costs to run.
 */
export class DuplicateClientPageNameError extends Error {
  public constructor(
    public readonly routeName: string,
    public readonly firstPageFile: string,
    public readonly secondPageFile: string,
  ) {
    super(
      `Two pages claim the client route name "${routeName}": "${firstPageFile}" and ` +
        `"${secondPageFile}". A route name identifies exactly one page, so the second ` +
        "page would be unreachable in the browser. To fix: rename one page's `route` " +
        "export, or move the file so its directory gives it a different route name.",
    );
    this.name = "DuplicateClientPageNameError";
  }
}

/**
 * Every literal the generator emits goes through here, without exception.
 * Windows separators, quotes and backslashes are all in scope, and a
 * hand-quoted literal that gets one of them wrong fails at bundle time with a
 * parse error no user can act on.
 */
function quote(value: string): string {
  return JSON.stringify(value);
}

const HEADER = [
  "// AUTO-GENERATED by @warlock.js/web — do not edit.",
  "// The page graph, compiled into the CLIENT bundle.",
  "//",
  "// `name` and `path` are baked in as data so the client runtime can match a",
  "// route before loading anything; every module reference is a dynamic",
  "// `import()` so a page's code is downloaded only when that page is rendered.",
  `import type { ClientPageEntry } from ${quote(CLIENT_RUNTIME_SPECIFIER)};`,
];

function assertUniqueNames(pages: readonly DiscoveredPage[]): void {
  const pageFileByName = new Map<string, string>();

  for (const page of pages) {
    const existing = pageFileByName.get(page.routeName);

    if (existing !== undefined) {
      throw new DuplicateClientPageNameError(page.routeName, existing, page.pageFile);
    }

    pageFileByName.set(page.routeName, page.pageFile);
  }
}

/**
 * One entry's `load`.
 *
 * It memoises NOTHING and holds no one-shot state: the runtime calls it again
 * on re-navigation to the same route, and a loader that works once and returns
 * undefined the second time is a silent blank page. Dynamic `import()` is
 * already module-cached by the bundler, so the correct implementation is to
 * let the cache do the caching.
 */
function loadSource(page: DiscoveredPage, toImportSpecifier: (file: string) => string): string[] {
  const bindings = ["Page"];
  const specifiers = [toImportSpecifier(page.pageFile)];

  // Outermost first, exactly as discovery enumerated the chain — the order IS
  // the nesting, so reordering it would silently reparent the page.
  const layoutBindings = page.layouts.map((layoutFile, index) => {
    bindings.push(`layout${index}`);
    specifiers.push(toImportSpecifier(layoutFile));

    return `layout${index}`;
  });

  if (page.appFile !== undefined) {
    bindings.push("App");
    specifiers.push(toImportSpecifier(page.appFile));
  }

  // `App` is OMITTED, never emitted as `App: undefined`: the runtime validator
  // reads an own `App` key as a promise that a module namespace is behind it.
  const app = page.appFile === undefined ? "" : ", App";

  return [
    "    load: async () => {",
    `      const [${bindings.join(", ")}] = await Promise.all([`,
    ...specifiers.map((specifier) => `        import(${quote(specifier)}),`),
    "      ]);",
    "",
    `      return { Page, layouts: [${layoutBindings.join(", ")}]${app} };`,
    "    },",
  ];
}

function entrySource(
  page: DiscoveredPage,
  toImportSpecifier: (file: string) => string,
): string[] {
  return [
    "  {",
    '    type: "page",',
    // Verbatim from discovery, both of them. `routePath` in particular is NOT
    // re-derived or re-normalised here: discovery already composed the layout
    // prefix with the declared route, and a second composition is a second
    // convention waiting to disagree with the server's.
    `    name: ${quote(page.routeName)},`,
    `    path: ${quote(page.routePath)},`,
    ...loadSource(page, toImportSpecifier),
    "  },",
  ];
}

/**
 * Returns the SOURCE of the client page registry module. Writes nothing.
 *
 * Zero pages is a legal result, not an error, and it is emitted as an explicit
 * empty registry: "built with web, no pages" must reach the runtime as a fact
 * rather than as a missing module.
 */
export function generateClientRegistry(options: GenerateClientRegistryOptions): string {
  const { pages, toImportSpecifier } = options;

  assertUniqueNames(pages);

  const declaration = `export const ${CLIENT_REGISTRY_EXPORT_NAME}: readonly ClientPageEntry[] =`;

  if (pages.length === 0) {
    return [...HEADER, "", `${declaration} [];`, ""].join("\n");
  }

  return [
    ...HEADER,
    "",
    `${declaration} [`,
    ...pages.flatMap((page) => entrySource(page, toImportSpecifier)),
    "];",
    "",
  ].join("\n");
}
